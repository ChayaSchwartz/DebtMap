import { ChangeDetectionStrategy, Component, computed, effect, inject, input, signal } from '@angular/core';
import { RouterLink } from '@angular/router';
import { toRiskBand, type FileDetailResponse, type RiskBand, type Severity } from '@debtmap/shared';
import { TranslatePipe } from '@ngx-translate/core';
import { AnalysisService, toUiMessage } from '../../core/analysis.service';
import { SEVERITY_BANDS, type UiMessage } from '../../core/ui-message';
import { LanguageService } from '../../core/language.service';

@Component({
  selector: 'app-file-detail',
  imports: [RouterLink, TranslatePipe],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './file-detail.html',
  styleUrl: './file-detail.scss',
})
export class FileDetailPage {
  private readonly analyses = inject(AnalysisService);
  private readonly languages = inject(LanguageService);

  readonly id = input.required<string>();
  readonly fileId = input.required<string>();

  protected readonly file = signal<FileDetailResponse | null>(null);
  protected readonly errorMessage = signal<UiMessage | null>(null);

  /**
   * Both languages arrive in one payload, generated by a single model call, so
   * switching the header toggle re-reads a field rather than costing a request
   * against the free tier's per-minute ceiling.
   */
  protected readonly summary = computed(() => {
    const explanation = this.file()?.explanation;
    if (!explanation) return null;
    return this.languages.language() === 'he' ? explanation.summaryHe : explanation.summaryEn;
  });

  protected readonly recommendation = computed(() => {
    const explanation = this.file()?.explanation;
    if (!explanation) return null;
    return this.languages.language() === 'he'
      ? explanation.recommendationHe
      : explanation.recommendationEn;
  });

  constructor() {
    effect(() => {
      const runId = this.id();
      const fileId = this.fileId();

      this.file.set(null);
      this.errorMessage.set(null);

      this.analyses.file(runId, fileId).subscribe({
        next: (detail) => this.file.set(detail),
        error: (error: unknown) => this.errorMessage.set(toUiMessage(error)),
      });
    });
  }

  protected band(score: number): RiskBand {
    return toRiskBand(score);
  }

  protected severityBand(severity: Severity): RiskBand {
    return SEVERITY_BANDS[severity];
  }
}
